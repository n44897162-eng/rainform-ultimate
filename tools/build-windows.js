#!/usr/bin/env node
/**
 * Rainform Ultimate - Windows installation packages (offline, no admin rights)
 * ---------------------------------------------------------------------------
 * electron-builder successfully produces dist/win-unpacked/ but its NSIS stage
 * needs the winCodeSign cache, whose macOS symlinks cannot be created without
 * SeCreateSymbolicLinkPrivilege on this machine. This script finishes the job
 * without that cache:
 *
 *   1. rebuild resources/app.asar from the CURRENT main/preload/www/icons
 *   2. compile a standard NSIS installer (per-user, uninstaller, shortcuts)
 *   3. compile a silent self-extracting portable launcher
 *
 * Output (project dist/):
 *   Rainform-Ultimate-Setup-1.0.0.exe
 *   Rainform-Ultimate-Portable-1.0.0.exe
 *
 *   node tools/build-windows.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const DESK = path.join(ROOT, 'app', 'desktop');
const UNPACKED = path.join(DESK, 'dist', 'win-unpacked');
const DIST = path.join(ROOT, 'dist');
const NSIS = path.join(ROOT, 'tools', '.nsis', 'pkg');
const MAKENSIS = path.join(NSIS, 'makensis.exe');
const ASAR = require(path.join(DESK, 'node_modules', '@electron', 'asar'));
const VER = require(path.join(DESK, 'package.json')).version;
const EXE_NAME = 'Rainform Ultimate.exe';

const SETUP = path.join(DIST, `Rainform-Ultimate-Setup-${VER}.exe`);
const PORTABLE = path.join(DIST, `Rainform-Ultimate-Portable-${VER}.exe`);
const w = p => p.replace(/\//g, '\\');

function need(p, label) {
  if (!fs.existsSync(p)) throw new Error('Missing ' + (label || p) + ': ' + p);
}
function step(s) { console.log('\n' + s); }

/* ------------------------------------------------------ 1. app.asar ---- */
async function buildAsar() {
  step('1/4  Rebuilding resources/app.asar from current sources');
  need(UNPACKED, 'electron-builder win-unpacked output');
  const stage = path.join(ROOT, 'tools', '.win-stage', 'app');
  fs.rmSync(stage, { recursive: true, force: true });
  fs.mkdirSync(stage, { recursive: true });
  const files = ['main.js', 'preload.js', 'package.json'];
  files.forEach(f => fs.copyFileSync(path.join(DESK, f), path.join(stage, f)));
  ['www', 'icons'].forEach(d => {
    const src = path.join(DESK, d), dst = path.join(stage, d);
    fs.mkdirSync(dst, { recursive: true });
    for (const e of fs.readdirSync(src, { withFileTypes: true })) {
      if (e.isDirectory()) continue;
      fs.copyFileSync(path.join(src, e.name), path.join(dst, e.name));
    }
  });
  const tmp = path.join(UNPACKED, 'resources', 'app.asar.tmp');
  const out = path.join(UNPACKED, 'resources', 'app.asar');
  await ASAR.createPackage(stage, tmp);
  // Atomic replace + settle time: Windows Defender / search indexer briefly
  // hold a freshly written file, and NSIS opens it during compilation.
  fs.rmSync(out, { force: true });
  fs.renameSync(tmp, out);
  console.log('   app.asar  ' + (fs.statSync(out).size / 1024).toFixed(1) + ' KB');
  console.log('   entries   ' + ASAR.listPackage(out).length);
  fs.rmSync(path.join(ROOT, 'tools', '.win-stage'), { recursive: true, force: true });
  // Confirm the handle is really released before handing the tree to NSIS.
  for (let i = 0; i < 20; i++) {
    try { const fd = fs.openSync(out, 'r'); fs.closeSync(fd); break; }
    catch (e) { await new Promise(r => setTimeout(r, 250)); }
  }
  await new Promise(r => setTimeout(r, 900));
}

/* --------------------------------------------------- 2. NSIS scripts --- */
function setupScript() {
  /* Classic NSIS pages instead of MUI2.
   * The NSIS 3.0.4.2 build distributed with electron-builder hangs at startup
   * under "/S" when MUI2 pages/plugins are present (the stub never reaches
   * .onInit, so silent/enterprise installs and CI smoke tests never finish).
   * Classic pages need no plugins, are skipped automatically in silent mode,
   * and still give end users a normal directory + progress GUI install.
   * Installer strings are kept ASCII because makensis reads .nsi as ACP. */
  return `; Rainform Ultimate installer - generated by tools/build-windows.js
!define APPNAME "Rainform Ultimate"
!define APPVER "${VER}"
!define APPEXE "${EXE_NAME}"
Name "\${APPNAME} \${APPVER}"
Caption "Rainform Ultimate \${APPVER} Setup"
OutFile "${w(SETUP)}"
InstallDir "$LOCALAPPDATA\\Programs\\Rainform Ultimate"
InstallDirRegKey HKCU "Software\\Rainform Ultimate" "InstallDir"
RequestExecutionLevel user
SilentInstall normal
SetCompressor /SOLID lzma
SetCompressorDictSize 64
DirText "Choose the folder where Rainform Ultimate will be installed." "Destination Folder" "Browse..." "Rainform Ultimate"
SubCaption 0 ": Destination Folder"
SubCaption 1 ": Installing"
CompletedText "Installation complete."
DetailsButtonText "Show details"
UninstallCaption "Rainform Ultimate \${APPVER} Uninstall"
UninstallButtonText "Uninstall"
UninstallSubCaption 0 ": Confirmation"
UninstallSubCaption 1 ": Removing"
Page directory
Page instfiles
UninstPage uninstConfirm
UninstPage instfiles

Section "Rainform Ultimate" SEC01
  SectionIn RO
  SetOutPath "$INSTDIR"
  File /r "${w(UNPACKED)}\\*.*"
  WriteUninstaller "$INSTDIR\\Uninstall.exe"
  WriteRegStr HKCU "Software\\Rainform Ultimate" "InstallDir" "$INSTDIR"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Rainform Ultimate" "DisplayName" "Rainform Ultimate"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Rainform Ultimate" "DisplayVersion" "\${APPVER}"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Rainform Ultimate" "Publisher" "Rainform"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Rainform Ultimate" "DisplayIcon" "$INSTDIR\\\${APPEXE}"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Rainform Ultimate" "UninstallString" "$INSTDIR\\Uninstall.exe"
  WriteRegDWORD HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Rainform Ultimate" "NoModify" 1
  WriteRegDWORD HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Rainform Ultimate" "NoRepair" 1
  CreateDirectory "$SMPROGRAMS\\Rainform Ultimate"
  CreateShortcut "$SMPROGRAMS\\Rainform Ultimate\\Rainform Ultimate.lnk" "$INSTDIR\\\${APPEXE}"
  CreateShortcut "$SMPROGRAMS\\Rainform Ultimate\\Uninstall.lnk" "$INSTDIR\\Uninstall.exe"
  CreateShortcut "$DESKTOP\\Rainform Ultimate.lnk" "$INSTDIR\\\${APPEXE}"
SectionEnd

Section "Uninstall"
  Delete "$DESKTOP\\Rainform Ultimate.lnk"
  Delete "$SMPROGRAMS\\Rainform Ultimate\\Rainform Ultimate.lnk"
  Delete "$SMPROGRAMS\\Rainform Ultimate\\Uninstall.lnk"
  RMDir "$SMPROGRAMS\\Rainform Ultimate"
  DeleteRegKey HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Rainform Ultimate"
  DeleteRegKey HKCU "Software\\Rainform Ultimate"
  SetOutPath "$TEMP"
  RMDir /r "$INSTDIR"
SectionEnd
`;
}

function portableScript() {
  return `; Rainform Ultimate portable launcher - silent self-extractor
!include "FileFunc.nsh"
SilentInstall silent
OutFile "${w(PORTABLE)}"
RequestExecutionLevel user
SetCompressor /SOLID lzma
SetCompressorDictSize 64
Name "Rainform Ultimate Portable ${VER}"

Section
  \${GetParameters} $R0
  StrCpy $R1 "$TEMP\\RainformPortable"
  SetOutPath "$R1"
  File /r "${w(UNPACKED)}\\*.*"
  ExecWait '"$R1\\${w(EXE_NAME)}" $R0' $R2
  SetOutPath "$TEMP"
  RMDir /r "$R1"
  SetErrorLevel 0
SectionEnd
`;
}

/* ---------------------------------------------------------- 3. compile - */
/** Fetch NSIS once from the mirror; subsequent builds are fully offline. */
async function ensureNsis() {
  if (fs.existsSync(MAKENSIS)) return;
  const cache = path.join(ROOT, 'tools', '.nsis');
  fs.mkdirSync(NSIS, { recursive: true });
  const arc = path.join(cache, 'nsis.7z');
  const url = 'https://npmmirror.com/mirrors/electron-builder-binaries/nsis-3.0.4.2/nsis-3.0.4.2.7z';
  console.log('   downloading NSIS 3.0.4.2 …');
  execFileSync('curl', ['-sL', '--max-time', '180', url, '-o', arc], { timeout: 200000 });
  const z7 = path.join(DESK, 'node_modules', '7zip-bin', 'win', 'x64', '7za.exe');
  need(z7, '7za.exe');
  execFileSync(z7, ['x', '-y', '-bd', arc, '-o' + NSIS], { timeout: 180000 });
  fs.rmSync(arc, { force: true });
  need(MAKENSIS, 'NSIS makensis.exe after extraction');
}

async function main() {
  await ensureNsis();
  fs.mkdirSync(DIST, { recursive: true });
  await buildAsar();

  step('2/4  Writing NSIS scripts');
  const setupNsi = path.join(ROOT, 'tools', '.nsis', 'setup.nsi');
  const portNsi = path.join(ROOT, 'tools', '.nsis', 'portable.nsi');
  fs.writeFileSync(setupNsi, setupScript(), 'utf8');
  fs.writeFileSync(portNsi, portableScript(), 'utf8');
  console.log('   ' + setupNsi);
  console.log('   ' + portNsi);

  step('3/4  Compiling installer + portable launcher');
  for (const [label, nsi] of [['Setup', setupNsi], ['Portable', portNsi]]) {
    // No /Vn switch: MSYS path mangling turns /V2 into a bogus script path.
    // Retry briefly: a transient file lock on app.asar surfaces here as
    // "File: failed opening file" even though the file is perfectly valid.
    let last;
    for (let attempt = 1; attempt <= 4; attempt++) {
      try {
        const out = execFileSync(MAKENSIS, [nsi], { encoding: 'utf8', cwd: NSIS, timeout: 600000 });
        console.log('   ' + label + ' (attempt ' + attempt + '): ' +
          String(out).trim().split('\n').slice(-2).join(' | ').slice(0, 220));
        last = null; break;
      } catch (e) {
        last = e;
        console.log('   ' + label + ' attempt ' + attempt + ' failed, retrying…');
        await new Promise(r => setTimeout(r, 1500));
      }
    }
    if (last) throw last;
  }

  step('4/4  Verifying outputs');
  [SETUP, PORTABLE].forEach(p => {
    need(p, 'built package');
    const s = fs.statSync(p);
    console.log('   ' + path.basename(p) + '  ' + (s.size / 1024 / 1024).toFixed(1) + ' MB');
  });
  console.log('\nDone. Packages are in ' + DIST);
}
main().catch(e => { console.error('BUILD FAILED: ' + e.message); process.exit(1); });
